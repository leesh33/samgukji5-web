/* 장수 성격 유형 — 충성도가 높으면 충신형, 낮으면 야심형이 먼저다 */
export function talkStyleOf(spec, loyalty) {
  if (!spec) return 'neutral';
  if (spec.custom) return 'custom';
  const loy = Number(loyalty) || 0;
  if (loy >= 88) return 'loyal';
  if (loy < 55) return 'ambitious';
  if ((spec.int || 0) >= 85 && (spec.int || 0) > (spec.war || 0)) return 'strategist';
  if ((spec.war || 0) >= 85) return 'warrior';
  return 'neutral';
}

/* 장수·턴에 따라 대사 한 벌을 고른다 — 턴이 바뀌면 다른 대사가 나온다 */
export function pickTalkLine(gid, spec, loyalty, turn) {
  const named = TALK_LINES[gid];
  const pool = (named && named.length) ? named : TALK_STYLES[talkStyleOf(spec, loyalty)];
  let h = 0;
  for (const ch of String(gid || '')) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const idx = (h + (Number(turn) || 1) * 7) % pool.length;
  return pool[idx];
}
